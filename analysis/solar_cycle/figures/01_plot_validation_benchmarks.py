from __future__ import annotations

r"""
FIGURE SUITE 1 — KOH2 VALIDATION BENCHMARKS
===========================================

Reads the real yearly point-weighted validation summaries produced previously
for IGS Final GIM and Madrigal GNSS TEC.

Creates:
  1) Four-panel bias/RMSE validation dashboard
  2) Correlation dashboard
  3) Compact CSV table used by the figures

Inputs are supplied at runtime with --igs-root and --madrigal-root.
"""

from pathlib import Path
import argparse
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

IGS_ROOT = Path("TEC_VALIDATION_IGS_2019_2026")
MAD_ROOT = Path("TEC_VALIDATION_MADRIGAL_2019_2026")
OUT = Path("01_VALIDATION_BENCHMARKS")
DPI = 400


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create KOH2 yearly IGS/Madrigal validation benchmark figures."
    )
    parser.add_argument("--igs-root", required=True, type=Path,
                        help="Directory containing the yearly IGS validation summary CSV.")
    parser.add_argument("--madrigal-root", required=True, type=Path,
                        help="Directory containing the yearly Madrigal validation summary CSV.")
    parser.add_argument("--output-dir", required=True, type=Path,
                        help="Directory for figure files and normalized plotting CSV.")
    return parser.parse_args()


def configure_runtime(args: argparse.Namespace) -> None:
    global IGS_ROOT, MAD_ROOT, OUT
    IGS_ROOT = args.igs_root.expanduser().resolve()
    MAD_ROOT = args.madrigal_root.expanduser().resolve()
    OUT = args.output_dir.expanduser().resolve()


def find_csv(root: Path, exact_names=(), patterns=()):
    """
    Prefer exact known filenames, then fall back to glob/rglob searches.
    """
    if not root.is_dir():
        raise FileNotFoundError(
            f"Validation output directory does not exist:\n    {root}"
        )

    for name in exact_names:
        path = root / name
        if path.is_file():
            return path

    for pattern in patterns:
        hits = sorted(root.glob(pattern))
        if hits:
            return hits[0]

    # Last fallback: recursive search in case results were moved into a subfolder.
    for pattern in patterns:
        hits = sorted(root.rglob(pattern))
        if hits:
            return hits[0]

    raise FileNotFoundError(
        f"No matching CSV in {root}\n"
        "Exact filenames tried:\n"
        + "\n".join(f"  {n}" for n in exact_names)
        + "\nPatterns tried:\n"
        + "\n".join(f"  {p}" for p in patterns)
    )


def load_summary(root: Path, reference: str):
    if reference == "IGS Final GIM":
        path = find_csv(
            root,
            exact_names=[
                "KOH2_2019_2026_IGS_validation_yearly_summary.csv",
            ],
            patterns=[
                "*IGS_validation_yearly_summary.csv",
                "*IGS*yearly*summary*.csv",
                "*yearly_summary.csv",
            ],
        )

    elif reference == "Madrigal GNSS TEC":
        path = find_csv(
            root,
            exact_names=[
                "KOH2_2019_2026_Madrigal_yearly_point_weighted_summary.csv",
            ],
            patterns=[
                "*Madrigal_yearly_point_weighted_summary.csv",
                "*Madrigal*point*weighted*summary*.csv",
                "*yearly_point_weighted_summary.csv",
            ],
        )

    else:
        raise ValueError(
            f"Unsupported reference: {reference}"
        )
    df = pd.read_csv(path)

    required = {"year", "comparison", "bias_tecu", "rmse_tecu", "pearson_r"}
    missing = required - set(df.columns)
    if missing:
        raise RuntimeError(f"{path} missing columns: {sorted(missing)}")

    df = df.copy()
    df["reference"] = reference

    def method_name(x):
        s = str(x)

        # Prefer the exact comparison identifiers generated by the validators.
        if s == "PyTECGg_VTEC_vs_IGS_IPP":
            return "PyTECGg VTEC"

        if s == "pyOASIS_VTEC_vs_IGS_IPP":
            return "pyOASIS VTEC"

        if s == "PyTECGg_VTEC_vs_Madrigal_IPP":
            return "PyTECGg VTEC"

        if s == "pyOASIS_VTEC_vs_Madrigal_IPP":
            return "pyOASIS VTEC"

        # Tolerant fallback for minor naming changes.
        lower = s.lower()

        if "pytecgg" in lower and "vtec" in lower and "veq" not in lower:
            return "PyTECGg VTEC"

        if "pyoasis" in lower and "vtec" in lower:
            return "pyOASIS VTEC"

        return None

    df["method"] = df["comparison"].map(method_name)
    df = df[df["method"].notna()].copy()

    for col in ["year", "bias_tecu", "rmse_tecu", "pearson_r"]:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    df = df.dropna(
        subset=["year", "bias_tecu", "rmse_tecu"]
    ).copy()

    if df.empty:
        raise RuntimeError(
            f"\nThe summary file was found, but no PyTECGg/pyOASIS VTEC rows "
            f"were recognized:\n    {path}\n\n"
            "Comparison values found:\n"
            + "\n".join(
                f"  {x}"
                for x in pd.read_csv(path)["comparison"].astype(str).unique()
            )
        )

    print()
    print(f"{reference} summary:")
    print(f"  file = {path}")
    print(f"  rows used = {len(df)}")
    print(
        "  years = "
        + ", ".join(
            str(int(y))
            for y in sorted(df["year"].dropna().unique())
        )
    )
    print(
        "  methods = "
        + ", ".join(sorted(df["method"].unique()))
    )

    return df, path


def plot_metric_panels(all_df: pd.DataFrame):
    fig, axes = plt.subplots(
        2, 2, figsize=(13, 8.5), sharex=True, constrained_layout=True
    )

    panels = [
        ("IGS Final GIM", "bias_tecu", "Bias (TECU)", "Bias vs IGS Final GIM"),
        ("IGS Final GIM", "rmse_tecu", "RMSE (TECU)", "RMSE vs IGS Final GIM"),
        ("Madrigal GNSS TEC", "bias_tecu", "Bias (TECU)", "Bias vs Madrigal"),
        ("Madrigal GNSS TEC", "rmse_tecu", "RMSE (TECU)", "RMSE vs Madrigal"),
    ]

    for ax, (ref, metric, ylabel, title) in zip(axes.ravel(), panels):
        sub = all_df[all_df["reference"] == ref]
        for method, g in sub.groupby("method"):
            g = g.sort_values("year")
            ax.plot(g["year"], g[metric], marker="o", linewidth=1.8, label=method)
        if metric == "bias_tecu":
            ax.axhline(0, linewidth=0.8)
        ax.set_title(title)
        ax.set_ylabel(ylabel)
        ax.grid(True, alpha=0.25)
        ax.legend(fontsize=8)

    for ax in axes[-1, :]:
        ax.set_xlabel("Year")

    fig.suptitle(
        "KOH2 VTEC comparison with external GNSS TEC reference products (2019–2026)",
        fontsize=15,
    )

    for ext in [".png", ".pdf", ".svg"]:
        fig.savefig(
            OUT / f"KOH2_validation_bias_RMSE_IGS_Madrigal{ext}",
            dpi=DPI if ext == ".png" else None,
            bbox_inches="tight",
        )
    plt.close(fig)


def plot_correlation(all_df: pd.DataFrame):
    fig, axes = plt.subplots(
        1, 2, figsize=(12, 4.8), sharey=True, constrained_layout=True
    )

    for ax, ref in zip(axes, ["IGS Final GIM", "Madrigal GNSS TEC"]):
        sub = all_df[all_df["reference"] == ref]
        for method, g in sub.groupby("method"):
            g = g.sort_values("year")
            ax.plot(
                g["year"], g["pearson_r"],
                marker="o", linewidth=1.8, label=method
            )
        ax.set_title(ref)
        ax.set_xlabel("Year")
        ax.set_ylim(0.55, 1.0)
        ax.grid(True, alpha=0.25)
        ax.legend(fontsize=8)

    axes[0].set_ylabel("Pearson r")
    fig.suptitle(
        "Temporal agreement of KOH2 VTEC solutions with external references",
        fontsize=14,
    )

    for ext in [".png", ".pdf", ".svg"]:
        fig.savefig(
            OUT / f"KOH2_validation_correlations_IGS_Madrigal{ext}",
            dpi=DPI if ext == ".png" else None,
            bbox_inches="tight",
        )
    plt.close(fig)


def main():
    configure_runtime(parse_args())

    OUT.mkdir(parents=True, exist_ok=True)

    igs, igs_path = load_summary(IGS_ROOT, "IGS Final GIM")
    mad, mad_path = load_summary(MAD_ROOT, "Madrigal GNSS TEC")

    all_df = pd.concat([igs, mad], ignore_index=True)
    all_df.to_csv(OUT / "KOH2_validation_benchmark_plot_data.csv", index=False)

    print("IGS input:", igs_path)
    print("Madrigal input:", mad_path)
    print("Rows used:", len(all_df))

    plot_metric_panels(all_df)
    plot_correlation(all_df)

    print("Output:", OUT)


if __name__ == "__main__":
    main()
